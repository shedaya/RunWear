import XCTest

/// Cross-platform engine fixtures (Stage 2 of the iOS parity plan, 2026-10-29).
///
/// Replays the committed `engine_fixtures.json` — generated FROM the shared
/// Kotlin `:engine` module (see EngineFixtureTest in RunWear-android, which
/// also asserts the same file on the JVM) — through the production
/// `OutfitRecommendationService`, which since Stage 2 delegates to that same
/// Kotlin code via the RunWearEngine framework. Identical inputs →
/// identical decisions is asserted from durable data on both platforms:
/// if the shared tables change, this test and its Kotlin twin both fail
/// until the fixture is regenerated and the diff reviewed.
///
/// The fixture inputs are the Stage 1 boundary frames: comfort-adjusted
/// and raw feels-like °F, measured rain + precipitation mm, mph wind,
/// percent humidity, UV index, location-local hour.
final class EngineFixtureTests: XCTestCase {

    private struct Fixture {
        let engineVersion: String
        let cases: [[String: Any]]
    }

    private func loadFixture() throws -> Fixture {
        let bundle = Bundle(for: EngineFixtureTests.self)
        let url = try XCTUnwrap(
            bundle.url(forResource: "engine_fixtures", withExtension: "json"),
            "engine_fixtures.json missing from the test bundle — it is committed permanently; do not delete it"
        )
        let data = try Data(contentsOf: url)
        let root = try XCTUnwrap(JSONSerialization.jsonObject(with: data) as? [String: Any])
        return Fixture(
            engineVersion: try XCTUnwrap(root["engineVersion"] as? String),
            cases: try XCTUnwrap(root["cases"] as? [[String: Any]])
        )
    }

    private func key(_ item: ClothingItem?) -> String? { item?.key }

    func testFixtureDecisionsMatchProductionService() throws {
        let fixture = try loadFixture()
        XCTAssertEqual(
            fixture.engineVersion, OutfitRecommendationService.engineVersion,
            "Fixture was generated by a different engine version than the shared module reports"
        )
        XCTAssertGreaterThan(fixture.cases.count, 2500, "Fixture grid suspiciously small")

        var mismatches: [String] = []
        for (index, fixtureCase) in fixture.cases.enumerated() {
            guard let input = fixtureCase["in"] as? [String: Any],
                  let expected = fixtureCase["out"] as? [String: Any] else {
                XCTFail("Malformed fixture case at index \(index)")
                return
            }
            let rec = OutfitRecommendationService.shared.getRecommendation(
                for: (input["adj"] as? NSNumber)?.doubleValue ?? .nan,
                rawTemperature: (input["raw"] as? NSNumber)?.doubleValue ?? .nan,
                isRaining: (input["rain"] as? NSNumber)?.boolValue ?? false,
                windSpeed: (input["wind"] as? NSNumber)?.doubleValue ?? .nan,
                humidity: (input["hum"] as? NSNumber)?.intValue ?? -1,
                uvIndex: (input["uv"] as? NSNumber)?.doubleValue ?? .nan,
                precipitation: (input["precip"] as? NSNumber)?.doubleValue ?? .nan,
                hour: (input["hour"] as? NSNumber)?.intValue ?? -1
            )

            func expectedKey(_ field: String) -> String? {
                guard let value = expected[field], !(value is NSNull) else { return nil }
                return value as? String
            }

            var problems: [String] = []
            if key(rec.topBase) != expectedKey("topBase") { problems.append("topBase \(key(rec.topBase) ?? "nil") != \(expectedKey("topBase") ?? "nil")") }
            if key(rec.topMid) != expectedKey("topMid") { problems.append("topMid \(key(rec.topMid) ?? "nil") != \(expectedKey("topMid") ?? "nil")") }
            if key(rec.topOuter) != expectedKey("topOuter") { problems.append("topOuter \(key(rec.topOuter) ?? "nil") != \(expectedKey("topOuter") ?? "nil")") }
            if key(rec.bottom) != expectedKey("bottom") { problems.append("bottom \(key(rec.bottom) ?? "nil") != \(expectedKey("bottom") ?? "nil")") }
            if key(rec.head) != expectedKey("head") { problems.append("head \(key(rec.head) ?? "nil") != \(expectedKey("head") ?? "nil")") }
            if key(rec.hands) != expectedKey("hands") { problems.append("hands \(key(rec.hands) ?? "nil") != \(expectedKey("hands") ?? "nil")") }

            let expectedAccessories = (expected["accessories"] as? [String]) ?? ["<missing>"]
            if rec.accessories.map(\.key) != expectedAccessories {
                problems.append("accessories \(rec.accessories.map(\.key)) != \(expectedAccessories)")
            }

            // Fixture tips are the engine's raw strings (leading emoji);
            // the bridge strips the emoji for Swift, so strip the fixture
            // side with the same function before comparing.
            let expectedTips = ((expected["tips"] as? [String]) ?? ["<missing>"]).map(EngineBridge.stripTipEmoji)
            if rec.tips != expectedTips {
                problems.append("tips \(rec.tips) != \(expectedTips)")
            }

            if !problems.isEmpty && mismatches.count < 10 {
                mismatches.append("case \(index) input=\(input): \(problems.joined(separator: "; "))")
            }
            if !problems.isEmpty && mismatches.count >= 10 && fixture.cases.count > 10 {
                // Keep counting cheap: stop collecting, but the assertion
                // below still fails on the collected evidence.
            }
        }

        XCTAssertTrue(
            mismatches.isEmpty,
            "Fixture mismatches (first \(mismatches.count)):\n\(mismatches.joined(separator: "\n"))"
        )
    }

    /// The user-visible tip text itself, pinned verbatim: the fixture
    /// comparison strips emoji from both sides with the same function, so
    /// these two cases additionally pin that what a user reads matches
    /// the pre-Stage-2 Swift port's exact wording.
    func testKnownTipTextsAreThePortedWording() {
        let cool = OutfitRecommendationService.shared.getRecommendation(
            for: 45, rawTemperature: 45, isRaining: false,
            windSpeed: 0, humidity: 50, uvIndex: 0, precipitation: 0, hour: 12
        )
        XCTAssertEqual(cool.tips, [
            "You should feel slightly cool stepping outside. If you're comfortable standing still, you're overdressed for running.",
            "Many runners still wear shorts at this temperature. Your legs generate plenty of heat — try it before adding tights."
        ])

        let hot = OutfitRecommendationService.shared.getRecommendation(
            for: 85, rawTemperature: 85, isRaining: false,
            windSpeed: 0, humidity: 50, uvIndex: 8, precipitation: 0, hour: 12
        )
        XCTAssertEqual(hot.tips, [
            "High heat risk — consider running early morning or evening.",
            "Hydrate well before, during, and after your run.",
            "UV is high — reapply sunscreen every 60-90 minutes if running longer than an hour."
        ])
    }

    /// Spot pins for the delegated hero mappings (the tables live in the
    /// shared module; these are the Stage 1 boundary-sensitive entries).
    func testHeroMappingSpotChecks() {
        XCTAssertEqual(HeroWeatherCondition.from(weatherCode: 66), .RAIN) // freezing rain
        XCTAssertEqual(HeroWeatherCondition.from(weatherCode: 71), .SNOW)
        XCTAssertEqual(HeroWeatherCondition.from(weatherCode: 3), .CLOUDY)
        XCTAssertEqual(HeroTempBracket.from(feelsLikeTemperature: 34.9), .COLD)
        XCTAssertEqual(HeroTempBracket.from(feelsLikeTemperature: 80), .HOT)
        XCTAssertEqual(HeroTimeOfDay.from(hour: 4), .NIGHT)
        XCTAssertEqual(HeroTimeOfDay.from(hour: 17), .DUSK)
    }
}
