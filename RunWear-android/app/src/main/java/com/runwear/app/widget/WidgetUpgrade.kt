package com.runwear.app.widget

import android.content.Context
import android.content.pm.PackageManager
import android.os.Build
import androidx.glance.appwidget.updateAll
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.launch

/**
 * Upgrade freshness guarantee (1.2.0, field regression Oct 27 2026).
 *
 * What the field proved: after Sol uninstalled the direct-download build
 * and installed 1.1.9 from Play, his home-screen widget kept showing the
 * OLD build's render — the centered, icon-less pre-1.1.8 Small
 * composition — with current data, and removing/re-adding the widget did
 * not change it. The shipped 1.1.9 artifacts provably contain the new
 * widget code (R8 mapping + dex literals + gates on the same tree), and
 * no composition in that code can produce the render he saw: those pixels
 * were RemoteViews generated by the previous build and restored by the
 * launcher / widget service across the uninstall→install. Nothing in the
 * app forced a recompose on a version change, so a restored render could
 * outlive the upgrade indefinitely.
 *
 * The guarantee: the first time a NEWER version of the app runs, every
 * widget instance is recomposed from the running code (updateAll). The
 * version stamp is written BEFORE the refresh is launched, so a crash
 * mid-refresh cannot loop the attempt on every start.
 */
object WidgetUpgrade {

    private const val PREFS_NAME = "widget_upgrade"
    private const val KEY_LAST_REFRESHED_VERSION = "last_refreshed_version_code"

    /** Pure decision, unit-tested: only a strictly newer version forces the recompose. */
    fun shouldForceRefresh(lastRefreshedVersionCode: Int, currentVersionCode: Int): Boolean =
        currentVersionCode > lastRefreshedVersionCode

    fun currentVersionCode(context: Context): Int = try {
        val info = context.packageManager.getPackageInfo(context.packageName, 0)
        if (Build.VERSION.SDK_INT >= 28) info.longVersionCode.toInt()
        else @Suppress("DEPRECATION") info.versionCode
    } catch (e: PackageManager.NameNotFoundException) {
        0
    }

    /**
     * Called from RunWearApp.onCreate. No-op unless the installed version
     * is newer than the last version that forced a refresh. On a fresh
     * install the stamp starts at 0, so the first run also stamps (and
     * harmlessly recomposes any just-placed widgets).
     */
    fun forceRefreshOnUpgrade(context: Context, scope: CoroutineScope) {
        val prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val last = prefs.getInt(KEY_LAST_REFRESHED_VERSION, 0)
        val current = currentVersionCode(context)
        if (!shouldForceRefresh(last, current)) return
        prefs.edit().putInt(KEY_LAST_REFRESHED_VERSION, current).apply()
        scope.launch {
            runCatching { OutfitWidget().updateAll(context) }
        }
    }
}
